// Build step. Usage: node build.mjs [theme]
//  1. theme/sprites/*.px  ->  theme/generated/*.svg   (ASCII pixel art -> crisp SVG rects)
//                         ->  theme/generated/sprites.meta.js  (sizes + twinkling-light positions)
//  2. theme/<name>.layout.json merged into layouts/devbench.base.json -> layouts/devbench.json
// .px format: "# scale N", "# K=#rrggbb ..." palette lines, then the grid ('.' = transparent).
// Optional "# upscale N" repeats every cell N x N (finer pixels, scale becomes scale/N) and
// "# outline #rrggbb T" adds a T-cell outline round the shape, so a thin border costs no hand drawing.
// Palette keys 1-4 are string lights: drawn dim in the SVG, and listed in the meta so a mod can
// blink an overlay pixel on top of each.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";

const LIGHT_KEYS = "1234";

// Pad the grid by t cells and mark every empty cell within t cells (8-way) of a shape cell with "X".
export function outline(grid, t) {
  const h = grid.length, w = grid[0].length;
  const at = (x, y) => grid[y - t]?.[x - t] ?? ".";
  const out = [];
  for (let y = 0; y < h + 2 * t; y++) {
    let row = "";
    for (let x = 0; x < w + 2 * t; x++) {
      let ch = at(x, y);
      if (ch === ".") {
        near: for (let dy = -t; dy <= t; dy++) for (let dx = -t; dx <= t; dx++) if (at(x + dx, y + dy) !== ".") { ch = "X"; break near; }
      }
      row += ch;
    }
    out.push(row);
  }
  return out;
}

export function parsePx(text, overrides = {}) {
  let scale = 1;
  const palette = {};
  const grid = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trimEnd();
    if (!line) continue;
    if (line.startsWith("#")) {
      const m = line.match(/^#\s*scale\s+(\d+)/);
      if (m) scale = Number(m[1]);
      for (const [, k, v] of line.matchAll(/(\S)=(#[0-9a-fA-F]{6})/g)) palette[k] = v;
    } else grid.push(line);
  }
  Object.assign(palette, overrides);
  const width = Math.max(...grid.map((r) => r.length));
  const ragged = grid.findIndex((r) => r.length !== width);
  if (ragged >= 0) throw new Error(`row ${ragged} is ${grid[ragged].length} wide, expected ${width}`);
  let cells = grid;
  const up = Number(text.match(/^#\s*upscale\s+(\d+)/m)?.[1] ?? 1);
  if (up > 1) cells = cells.flatMap((r) => Array(up).fill([...r].map((c) => c.repeat(up)).join("")));
  const ol = text.match(/^#\s*outline\s+(#[0-9a-fA-F]{6})\s+(\d+)/m);
  if (ol) {
    palette.X = ol[1];
    cells = outline(cells, Number(ol[2]));
  }
  const cols = cells[0].length;
  const lights = [];
  cells.forEach((row, y) => [...row].forEach((ch, x) => {
    if (LIGHT_KEYS.includes(ch) && palette[ch]) lights.push({ x, y, c: palette[ch] });
  }));
  return { scale: scale / up, palette, grid: cells, cols, rows: cells.length, lights };
}

export function pxToSvg(text, overrides = {}) {
  const { scale, palette, grid, cols, rows } = parsePx(text, overrides);
  const rects = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let n = 1;
      while (row[x + n] === ch) n++;
      if (ch !== "." && ch !== " ") {
        if (!palette[ch]) throw new Error(`sprite colour '${ch}' not in palette (row ${y})`);
        const dim = LIGHT_KEYS.includes(ch) ? ' fill-opacity="0.35"' : "";
        rects.push(`<rect x="${x}" y="${y}" width="${n}" height="1" fill="${palette[ch]}"${dim}/>`);
      }
      x += n;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${cols} ${rows}" width="${cols * scale}" height="${rows * scale}" shape-rendering="crispEdges">${rects.join("")}</svg>\n`;
}

const merge = (a, b) => {
  for (const [k, v] of Object.entries(b)) {
    a[k] = v && typeof v === "object" && !Array.isArray(v) && a[k] && typeof a[k] === "object" && !Array.isArray(a[k]) ? merge(a[k], v) : v;
  }
  return a;
};

if (process.argv[1] && process.argv[1].endsWith("build.mjs")) {
  const name = process.argv[2] ?? "christmas";
  mkdirSync("theme/generated", { recursive: true });
  const meta = {};
  for (const f of readdirSync("theme/sprites").filter((f) => f.endsWith(".px"))) {
    const text = readFileSync(`theme/sprites/${f}`, "utf8");
    const key = f.replace(/\.px$/, "");
    const { scale, cols, rows, lights } = parsePx(text);
    meta[key] = { scale, cols, rows, lights };
    writeFileSync(`theme/generated/${key}.svg`, pxToSvg(text));
    console.log(`sprite ${f} (${cols}x${rows}, ${lights.length} lights)`);
  }
  writeFileSync("theme/generated/sprites.meta.js", `// Generated by build.mjs. Do not edit.\nexport const SPRITES = ${JSON.stringify(meta, null, 2)};\n`);
  const base = JSON.parse(readFileSync("layouts/devbench.base.json", "utf8"));
  const paint = JSON.parse(readFileSync(`theme/${name}.layout.json`, "utf8"));
  const walk = (n) => { if (paint[n.id]) merge(n, paint[n.id]); (n.children ?? []).forEach(walk); };
  walk(base);
  base.theme = name;
  writeFileSync("layouts/devbench.json", JSON.stringify(base, null, 2));
  console.log(`built layouts/devbench.json with theme ${name}`);
}
